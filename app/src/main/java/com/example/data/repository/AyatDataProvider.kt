    fun getPageBenefits(page: Int): PageBenefits {
        if (QuranDatabaseHelper.isReady()) {
            val benefits = QuranDatabaseHelper.getPageBenefits(page)
            if (benefits.isNotEmpty()) {
                return PageBenefits(page, benefits)
            }
        }
        return pageBenefitsMap[page] ?: PageBenefits(
            pageNumber = page,
            benefits = listOf(
                "تدبر هدايات القرآن الكريم واستحضار عظمة كلام الله تعالى في هذه الصفحة المباركة.",
                "المسارعة في العمل الصالح والتزام أوامر الله ونواهيه الواردة في الآيات الكريمة.",
                "الاستعانة بالله بالدعاء والصبر والاستغفار في كل الأحوال والأوقات."
            )
        )
    }

    // Helper to get Hizb & Quarter label for any page
    fun getHizbQuarterLabelForPage(page: Int): String {
        val quarter = quranQuarters.lastOrNull { it.pageNumber <= page }
        return if (quarter != null) {
            "${quarter.quarterLabel}"
        } else {
            val juz = QuranDataProvider.getJuzForPage(page)
            "الجزء $juz"
        }
    }

